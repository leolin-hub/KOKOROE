/**
 * DX 編碼：底片罐身上那排黑銀相間的格子。
 *
 * 真實的 135 底片罐上有一塊 2 × 6 的格子（DX CAS code）。相機裡的接點碰到「裸金屬」會導電、
 * 碰到「塗漆」不導電，相機靠這組開關讀出 ISO、張數與寬容度，自動設定感光度。
 * 罐子上銀色的格子就是裸金屬，黑色的是塗漆。
 *
 * 這裡的 `true` 代表裸金屬（畫成銀色）、`false` 代表塗漆（畫成黑色）。
 */

/** 一排六格，由左到右。 */
export type DxRow = readonly boolean[]

export interface DxCode {
  row1: DxRow
  row2: DxRow
}

/**
 * 每個 ISO 對應的「速度位元」（第一排的第 2～6 格），用 `'1'`／`'0'` 字串表示，`'1'` 是裸金屬。
 *
 * 【你來填】DX 標準只定義了一組固定的 ISO（25、32、40、50、64、80、100……5000，每 1/3 級一個）。
 * 請照可信的來源抄，例如 Wikipedia 的「DX encoding」條目裡的 CAS 表。
 * 我沒有把握記得每一格正確，所以這張表不幫你填 —— 填錯的話畫面不會壞，只是罐子上的格子不是真的。
 * 至少填你手上有的：100、200、400、800。
 */
export const DX_SPEED_BITS: Readonly<Record<number, string>> = {}

/**
 * 依 ISO 產生罐身的 DX 格子。
 *
 * 【影響畫面】唱片櫃裡底片罐的背面（焦點卷期滑鼠移上去轉動時看得到），左下角那塊 2 × 6 的黑銀格子。
 *
 * 格子的配置（請一樣對照來源確認）：
 *   第一排：[接地, 速度1, 速度2, 速度3, 速度4, 速度5]   第 1 格一定是裸金屬
 *   第二排：[接地, 張數1, 張數2, 張數3, 寬容度1, 寬容度2] 第 1 格一定是裸金屬
 * 張數與寬容度目前沒有資料（卷期沒有張數欄位），先固定用 36 張、±1 級對應的位元（一樣查表）。
 *
 * 【預期結果】（假設 DX_SPEED_BITS 已經填了 400）
 *   dxCode(400).row1.length === 6，而且 row1[0] === true
 *   dxCode(400).row1 的第 2～6 格 === DX_SPEED_BITS[400] 逐字轉成的 boolean
 *   dxCode(123)  → 用表裡最接近 123 的 ISO（應該是 125）
 *   dxCode(400) 在 DX_SPEED_BITS 是空的時候 → 不 crash，第 2～6 格全部 false
 *
 * 【會用到】（都是內建的，不用 import）
 *   - `Object.keys(DX_SPEED_BITS).map(Number)`：物件的 key 永遠是字串，要轉回數字才能比大小
 *   - `array.reduce((best, x) => ..., first)`：找「差距最小」的那一個
 *   - `Math.abs(a - b)`
 *   - `str.split('')` 把 `'10010'` 拆成 `['1','0','0','1','0']`，再 `.map((c) => c === '1')`
 *   - `[true, ...rest]`：展開運算子，把接地那一格接在最前面
 *
 * 【步驟】
 * 0. 刪掉 `void iso` 與佔位的 `return`。
 * 1. 找最接近的 ISO：先拿到表裡所有 ISO 的數字陣列；陣列是空的就直接用 `'00000'`。
 * 2. 用 `reduce` 找出和 `iso` 差距最小的那一個，取出它的位元字串。
 * 3. 把位元字串轉成 boolean 陣列，前面接上接地格：`row1 = [true, ...bits]`。
 * 4. 第二排：接地格 + 36 張與 ±1 級的五個位元（查表後寫成常數）。
 *
 * 【坑】
 * - `Object.keys` 回傳的是字串：`'100' < '25'` 是 true（字串比的是字典序），不轉數字就比錯。
 * - 位元字串長度要剛好 5，少一格的話整排會少一格，罐子上的格子會缺角。可以 `.padEnd(5, '0')` 保險。
 *
 * 【可以想一下】這是「位元」最直觀的樣子：每一格就是一個 0 或 1。
 *   同樣的資訊也可以存成一個整數（例如 `0b10010`），用 `(n >> i) & 1` 取出第 i 位 —— 想試的話可以改寫看看。
 */
export function dxCode(iso: number): DxCode {
  void iso
  return {
    row1: [true, false, false, false, false, false],
    row2: [true, false, false, false, false, false],
  }
}
